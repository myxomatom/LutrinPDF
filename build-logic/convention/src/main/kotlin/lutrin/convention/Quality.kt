/** Generated classes that carry no hand-written logic and must not count in coverage. */
private val COVERAGE_EXCLUDED_CLASSES =
    listOf(
        "*_Factory",
        "*_Factory\$*",
        "*_MembersInjector",
        "*_Provide*Factory",
        "HiltWrapper_*",
        "*.di.*Module",
        "*.di.*Module\$*",
        "*_HiltModules*",
        "*_GeneratedInjector",
        "*_ComponentTreeDeps",
        "*Hilt_*",
        "dagger.hilt.internal.*",
        "hilt_aggregated_deps.*",
        "*.BuildConfig",
        "*.ComposableSingletons*",
        // Room: database and DAO implementations generated by its compiler.
        "*_Impl",
        "*_Impl\$*",
    )

/**
 * Applies the quality tools shared by every module: ktlint, detekt (with Compose rules),
 * Kover and Dokka (`AGENTS.md` §4–§6), and keeps the unit-test JVMs' temporary files in the
 * build directory ([configureTestTempDir]).
 */
internal fun Project.configureQuality() {
    configureStaticAnalysis()
    with(pluginManager) {
        apply(libs.pluginId("kover"))
        apply(libs.pluginId("dokka"))
    }
    configureKover()
    configureDokka()
    configureTestTempDir()
}

/**
 * Applies the style and static analysis tools only (ktlint, detekt), for modules that ship
 * neither code to cover nor API to document, such as the `:benchmark` test module.
 */
internal fun Project.configureStaticAnalysis() {
    with(pluginManager) {
        apply(libs.pluginId("ktlint"))
        apply(libs.pluginId("detekt"))
    }
    configureKtlint()
    configureDetekt()
}

private fun Project.configureKtlint() {
    extensions.configure<KtlintExtension> {
        version.set(libs.version("ktlint"))
    }
}

private fun Project.configureDetekt() {
    extensions.configure<DetektExtension> {
        buildUponDefaultConfig = true
        parallel = true
        config.setFrom(rootProject.layout.projectDirectory.file("config/detekt/detekt.yml"))
        // src/benchmark: code of the app's benchmark builds only (ADR 0012). src/sharedTest:
        // test code compiled into both the JVM and the instrumented tests (core:pdf, ADR 0025).
        source.setFrom(
            "src/main/kotlin",
            "src/test/kotlin",
            "src/androidTest/kotlin",
            "src/sharedTest/kotlin",
            "src/benchmark/kotlin",
        )
    }
    dependencies {
        "detektPlugins"(libs.library("compose-rules-detekt"))
    }
    // detekt 1.23 embeds its own Kotlin compiler: keep its classpath on that exact version,
    // otherwise the project's newer Kotlin would leak into detekt and break it.
    val detektKotlin = libs.version("detektKotlin")
    configurations.named("detekt") {
        resolutionStrategy.eachDependency {
            if (requested.group == "org.jetbrains.kotlin") useVersion(detektKotlin)
        }
    }
    // detekt defaults its --jvm-target to the JVM running Gradle, and its compiler rejects
    // recent ones ("Invalid value (25) passed to --jvm-target"): analyse at the project level.
    val jvmTarget = JAVA_VERSION.toString()
    tasks.withType<Detekt>().configureEach { this.jvmTarget = jvmTarget }
    tasks.withType<DetektCreateBaselineTask>().configureEach { this.jvmTarget = jvmTarget }
}

private fun Project.configureKover() {
    extensions.configure<KoverProjectExtension> {
        reports.filters.excludes {
            classes(COVERAGE_EXCLUDED_CLASSES)
            annotatedBy("androidx.compose.ui.tooling.preview.Preview")
        }
    }
}

private fun Project.configureDokka() {
    extensions.configure<DokkaExtension> {
        // Must match the "# Module" heading of the module's Module.md.
        moduleName.set(path.removePrefix(":"))
        // No network access while building, like the app itself: no links to external API docs.
        dokkaSourceSets.configureEach { enableJdkDocumentationLink.set(false) }
        dokkaSourceSets.configureEach { enableAndroidDocumentationLink.set(false) }
        dokkaSourceSets.configureEach { enableKotlinStdLibDocumentationLink.set(false) }
        dokkaSourceSets.configureEach {
            includes.from(layout.projectDirectory.file("Module.md"))
            reportUndocumented.set(true)
        }
        dokkaPublications.configureEach {
            // Dokka 2.3 warns about a KDoc link unresolved in androidx itself (Lifecycle.State in
            // MenuHost, inherited by MainActivity). Neither suppressInheritedMembers nor a
            // perPackageOption on androidx silences it, so :app alone tolerates warnings.
            failOnWarning.set(path != ":app")
        }
    }
}
