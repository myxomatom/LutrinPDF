package io.github.myxomatom.lutrin.feature.about

import com.mikepenz.aboutlibraries.Libs

/**
 * One third-party component shipped in the app: a Maven library found by Gradle, or something
 * Gradle cannot see (MuPDF and its native libraries, fonts, hyphenation patterns), declared by
 * hand in `app/aboutlibraries/` (ADR 0030).
 *
 * @property id stable unique identifier (`group:artifact` for a library).
 * @property name display name.
 * @property version version shipped, or `null` when unknown.
 * @property description one-line description, or `null`.
 * @property website home page of the project, shown as text only (never opened), or `null`.
 * @property authors names of the authors or the organisation.
 * @property licenses the licenses it is distributed under, with their full text.
 */
data class LicensedComponent(
    val id: String,
    val name: String,
    val version: String?,
    val description: String?,
    val website: String?,
    val authors: List<String>,
    val licenses: List<LicenseText>,
) {
    /** Names of the licenses on one line, as shown in the list (`MIT, Apache-2.0`). */
    val licenseSummary: String get() = licenses.joinToString(", ") { it.name }
}

/**
 * A license a component is distributed under.
 *
 * @property name short name (`Apache-2.0`).
 * @property text full text with its copyright notice, or `null` when none was generated.
 */
data class LicenseText(val name: String, val text: String?)

/**
 * Reads the JSON generated by AboutLibraries into the components shown in E4, sorted by name
 * (case-insensitive) then identifier, so that the order never depends on the order of the file.
 *
 * @param json content of `aboutlibraries.json`.
 * @return the components, without duplicate identifier. Empty when [json] is not a valid
 *   AboutLibraries document: the parser logs the cause and returns nothing instead of failing.
 */
internal fun parseComponents(json: String): List<LicensedComponent> = Libs.Builder().withJson(json).build().libraries
    .map { library ->
        LicensedComponent(
            id = library.uniqueId,
            name = library.name,
            version = library.artifactVersion?.takeIf { it.isNotBlank() },
            description = library.description?.takeIf { it.isNotBlank() },
            website = library.website?.takeIf { it.isNotBlank() },
            authors = library.developers.mapNotNull { it.name?.takeIf(String::isNotBlank) }.distinct(),
            licenses = library.licenses.map { LicenseText(it.name, it.licenseContent?.takeIf(String::isNotBlank)) },
        )
    }
    .distinctBy { it.id }
    .sortedWith(compareBy(String.CASE_INSENSITIVE_ORDER, LicensedComponent::name).thenBy { it.id })
